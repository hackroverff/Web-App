const humanize = (key) =>
  key
    .split(/[.\-_]/)
    .filter(Boolean)
    .join(' ')
    .replace(/^./, (c) => c.toUpperCase());

export function t(key, vars) {
  const pair = DICT[key];
  const lang = document.documentElement.lang === 'ta' ? 1 : 0;
  let out = pair ? pair[lang] || pair[0] : humanize(key);
  if (vars) out = out.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] === undefined || vars[name] === null ? '' : String(vars[name])));
  return out;
}

export const isTamil = () => document.documentElement.lang === 'ta';

/** Picks the Tamil product name when the UI is in Tamil and the store provided one. */
export function localName(item, nameKey = 'name', taKey = 'name_ta') {
  if (isTamil() && item?.[taKey]) return item[taKey];
  return item?.[nameKey] || '';
}

